const NUMBER = new Intl.NumberFormat("it-IT", { maximumFractionDigits: 0, useGrouping: "always" });
const SCORE = new Intl.NumberFormat("it-IT", { minimumFractionDigits: 1, maximumFractionDigits: 1 });

/** Un intero in italiano («1.200»). */
export function formatCount(n: number): string {
  return NUMBER.format(Math.max(0, Math.trunc(n)));
}

/** Un punteggio da 0 a 5 con una cifra decimale e la virgola («3,1»); null se manca. */
export function formatScore(score: number | null | undefined): string | null {
  return typeof score === "number" && Number.isFinite(score) ? SCORE.format(score) : null;
}

