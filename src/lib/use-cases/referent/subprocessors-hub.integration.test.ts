type ResolveResult = { url: string; shortCircuit?: boolean };
type LoadResult = { format?: string; source?: string | Uint8Array; shortCircuit?: boolean };
const { registerHooks } = nodeModule as unknown as {
  registerHooks(hooks: {
    resolve?(specifier: string, context: object, nextResolve: (specifier: string, context: object) => ResolveResult): ResolveResult;
    load?(url: string, context: object, nextLoad: (url: string, context: object) => LoadResult): LoadResult;
  }): void;
};

function signIn(person: Person | null): void {
  (globalThis as { __subSession?: unknown }).__subSession = person ? { user: { id: ids[person], email: emails[person], emailVerified: true, name: `Persona ${person}` } } : null;
}

test("preparazione: la sessione della prova e i componenti", opts, async () => {
  const stub = (source: string) => `data:text/javascript,${encodeURIComponent(source)}`;
  const stubs: Record<string, string> = {
    "@/lib/auth": stub("export async function auth() { return globalThis.__subSession ?? null; }"),
    "next/cache": stub("export function revalidatePath() {}\nexport function revalidateTag() {}\nexport function refresh() {}"),
  };
  const { default: ts } = await import("typescript");
  registerHooks({
    resolve(specifier, context, nextResolve) {
      if (Object.hasOwn(stubs, specifier)) return { url: stubs[specifier], shortCircuit: true };
      return nextResolve(specifier, context);
    },
    load(moduleUrl, context, nextLoad) {
      if (!moduleUrl.startsWith("file:") || !moduleUrl.endsWith(".tsx")) return nextLoad(moduleUrl, context);
      const file = fileURLToPath(moduleUrl);
      const { outputText } = ts.transpileModule(readFileSync(file, "utf8"), {
        fileName: file,
        compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX },
      });
      return { format: "module", source: outputText, shortCircuit: true };
    },
  });
  assert.equal(process.env.UC_ENABLED, undefined, "i dossier sono spenti");
});

test("la scheda c'è per un workspace dell'area senza i dossier, e l'autorizzazione si registra", opts, async () => {
  const { SubprocessorsCard } = await import("../../../components/workspace/subprocessors-card.tsx");
  const card = await SubprocessorsCard({ workspaceId: ids.ws, workspaceName: "TopJet prova", userId: ids.builder, workspaceRole: "function_lead" });
  assert.ok(card, "la scheda si mostra");
  const off = await SubprocessorsCard({ workspaceId: randomUUID(), workspaceName: "Fuori dall'area", userId: ids.builder, workspaceRole: "function_lead" });
  assert.equal(off, null, "fuori dall'area niente");
  signIn("builder");
  const { declareSubprocessorsAction } = await import("../../actions/uc-subprocessors.ts");
  const result = await declareSubprocessorsAction(ids.ws, "2026-10", true);
  assert.ok(result.ok, JSON.stringify(result));
  const acks = await q(`SELECT list_version FROM uc_subprocessor_acks WHERE workspace_id = $1::uuid`, [ids.ws]);
  assert.deepEqual(acks.map((a) => a.list_version), ["2026-10"]);
  // Ora «Chiedi al referente» non ha più la porta dei fornitori.
  ok(await referents.prepareReferentQuestions(as("builder"), ids.useCase));
  const sent = await referents.sendReferentRequest(as("builder"), ids.useCase, { contact: { kind: "nuovo", displayName: "Mario Rossi", email: REFERENT_EMAIL }, needIds: (await needIds()).slice(0, 1) }, { env: ENV, requester: requester("builder") });
  assert.ok(sent.ok, JSON.stringify(sent));
});

test("con la funzione spenta e senza dossier la scheda non c'è; l'action risponde che la sezione è spenta", opts, async () => {
  const { SubprocessorsCard } = await import("../../../components/workspace/subprocessors-card.tsx");
  process.env.USE_CASE_REFERENTS = "off";
  try {
    assert.equal(await SubprocessorsCard({ workspaceId: ids.other, workspaceName: "Altro", userId: ids.builder, workspaceRole: "function_lead" }), null);
    signIn("builder");
    const { declareSubprocessorsAction } = await import("../../actions/uc-subprocessors.ts");
    const result = await declareSubprocessorsAction(ids.other, "2026-10", true);
    assert.equal(result.ok, false);
    assert.equal((await q(`SELECT 1 FROM uc_subprocessor_acks WHERE workspace_id = $1::uuid`, [ids.other])).length, 0);
  } finally {
    delete process.env.USE_CASE_REFERENTS;
  }
});

