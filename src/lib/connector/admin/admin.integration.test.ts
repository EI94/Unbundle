// Opt-in integration suite for package K8 (prompt WP8) on the connector's own local cluster:
// scripts/connector-admin.ts on a synthetic workspace. Every dry run, before and after each
// --apply, must leave the database exactly as it was (rows of the connector config, codes
// of the contributions, tokens); --apply writes only with the confirmations; what the script
// loads (config, profile, guide, token, codes) is what the real route then serves.
//   node scripts/connettore-test/run-db-tests.mjs
// Same guards as the other connector suites. Synthetic data, created and deleted here; the
// test token is generated by the script and never printed.
const url = process.env.DATABASE_URL;
const enabled = process.env.CONN_TEST_ISOLATED === "true" && Boolean(url);
if (enabled) {
  const parsed = new URL(url!);
  if (parsed.hostname !== "127.0.0.1" || process.env.UC_TEST_DATABASE_URL !== url) {
    throw new Error("Connector DB tests need a loopback DATABASE_URL equal to UC_TEST_DATABASE_URL");
  }
  if ((globalThis.fetch as { name?: string }).name !== "localNeonFetch") {
    throw new Error("Preload scripts/uc-test/local-neon.cjs to reach the local test database");
  }
}
const opts = { skip: !enabled };

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const suffix = randomBytes(3).toString("hex");
const ids = { org: randomUUID(), wsA: randomUUID(), wsB: randomUUID() };
const slug = `k8-a-${suffix}`;
const GUIDE_FILE = join(repoRoot, "docs/connettore/guida-esempio.json");
const TITLES = [`Qualità dei verbali di riunione ${suffix}`, `Archivio delle offerte firmate ${suffix}`, `Promemoria delle scadenze dei documenti ${suffix}`];
const fakeAlertDeps: ExposedTokenAlertDeps = { findAdminChannel: async () => null, post: async () => undefined };

let q: (text: string, params?: unknown[]) => Promise<Record<string, unknown>[]>;
let admin: typeof import("./main.ts").runConnectorAdmin;
let handle: (request: Request, slug: string, deps: ConnectorHandlerDeps) => Promise<Response>;
let routeDeps: ConnectorHandlerDeps;
let dir = "";
let configFile = "";
let profileFile = "";
let fingerprintDb = "";
let token = "";
const captured: string[] = [];
const originalConsole = { log: console.log, info: console.info, warn: console.warn, error: console.error };

function confirmations(environment = "local", database = fingerprintDb) {
  return ["--apply", "--confirm-authorized", "--confirm-database", database, "--environment", environment];
}

async function run(argv: string[]): Promise<AdminOutcome & { printed: AdminOutput[] }> {
  const printed: AdminOutput[] = [];
  const outcome = await admin(argv, { env: { CONNECTOR_ADMIN_DATABASE_URL: url }, print: (o) => printed.push(o) });
  return { ...outcome, printed };
}

/** Tutto ciò che lo script può scrivere per i due workspace, in un testo solo. */
async function snapshot(): Promise<string> {
  const workspaces = [ids.wsA, ids.wsB];
  const configs = await q(`SELECT to_jsonb(c) AS row FROM workspace_connector_configs c WHERE workspace_id = ANY($1::uuid[]) ORDER BY workspace_id`, [workspaces]);
  const codes = await q(`SELECT id::text, code, updated_at::text FROM use_cases WHERE workspace_id = ANY($1::uuid[]) ORDER BY id`, [workspaces]);
  const tokens = await q(`SELECT to_jsonb(t) AS row FROM workspace_integration_tokens t WHERE workspace_id = ANY($1::uuid[]) ORDER BY id`, [workspaces]);
  return JSON.stringify({ configs, codes, tokens });
}

async function dryRunsWriteNothing(label: string, argvs: string[][]) {
  const before = await snapshot();
  for (const argv of argvs) {
    const out = await run(argv);
    assert.notEqual(out.output.status, "APPLIED", `${label} ${argv[0]}`);
    assert.equal(out.printed.length, 0, `${label} ${argv[0]}: nessun piano a secco`);
    assert.equal(await snapshot(), before, `${label} ${argv[0]}: la prova a secco ha scritto`);
  }
}

const everyDryRun = () => [
  ["config", "--workspace", ids.wsA, "--file", configFile],
  ["profile", "--workspace", ids.wsA, "--file", profileFile],
  ["guide", "--workspace", ids.wsA, "--file", GUIDE_FILE],
  ["token", "--workspace", ids.wsA],
  ["backfill-codes", "--workspace", ids.wsA],
  ["config", "--workspace", ids.wsB, "--file", configFile],
];

before(async () => {
  if (!enabled) return;
  for (const level of ["log", "info", "warn", "error"] as const) {
    console[level] = (...args: unknown[]) => {
      captured.push(args.map((a) => (typeof a === "string" ? a : JSON.stringify(a))).join(" "));
      originalConsole[level](...args);
    };
  }
  const { neon } = await import("@neondatabase/serverless");
  const sql = neon(url!);
  q = (text, params = []) => sql.query(text, params) as Promise<Record<string, unknown>[]>;
  const [main, appTools, handler] = await Promise.all([import("./main.ts"), import("../app-tools.ts"), import("../handler.ts")]);
  admin = main.runConnectorAdmin;
  handle = handler.handleConnectorRequest;
  routeDeps = appTools.appConnectorHandlerDeps({ schedule: () => {}, env: { MCP_CONNECTOR_ENABLED: "true" }, alertDeps: fakeAlertDeps });
  const target = new URL(url!);
  fingerprintDb = `${target.hostname}:${target.port}${target.pathname}`;

  dir = mkdtempSync(join(tmpdir(), "k8-admin-"));
  configFile = join(dir, "config.json");
  writeFileSync(configFile, JSON.stringify({ slug, codePrefix: "XK", workspaceDisplayName: "Alfa e Beta", allowedDomains: ["alfa.test"] }));
  // Il file d'esempio del repository (uguale a EXAMPLE_PROFILE_FILE: profile.test.ts).
  profileFile = join(repoRoot, "docs/connettore/profilo-esempio.json");

  await q(`INSERT INTO organizations (id, name, slug) VALUES ($1, 'Organizzazione di prova K8', $2)`, [ids.org, `org-k8-${suffix}`]);
  for (const [id, name] of [[ids.wsA, "A"], [ids.wsB, "B"]]) {
    await q(`INSERT INTO workspaces (id, organization_id, name) VALUES ($1, $2, $3)`, [id, ids.org, `Workspace K8 ${name} ${suffix}`]);
  }
  // Tre segnalazioni di A senza codice (nate prima del connettore), inviate in quest'ordine: 2, 0, 1.
  const at = ["2026-09-03 09:00:00", "2026-09-04 09:00:00", "2026-09-01 09:00:00"];
  for (const [i, title] of TITLES.entries()) {
    await q(`INSERT INTO use_cases (workspace_id, title, description, status, submitted_at, source) VALUES ($1, $2, 'Segnalazione di prova.', 'proposed', $3, 'web_proposed')`, [ids.wsA, title, at[i]]);
  }
  // B: la riga di D6 (use-case-admin configs), spenta, slug e prefisso generati.
  await q(`INSERT INTO workspace_connector_configs (workspace_id, slug, code_prefix) VALUES ($1, $2, 'WKB')`, [ids.wsB, `workspace-k8-b-${suffix}`]);
});

after(async () => {
  if (!enabled) return;
  Object.assign(console, originalConsole);
  if (dir) rmSync(dir, { recursive: true, force: true });
  await q(`DELETE FROM connector_rate_limits WHERE bucket LIKE ANY($1::text[])`, [[`%${ids.wsA}%`, `%${ids.wsB}%`]]);
  await q(`DELETE FROM connector_rate_limits WHERE bucket IN (SELECT 'conn:' || id::text || ':read' FROM workspace_integration_tokens WHERE workspace_id = $1)`, [ids.wsA]);
  await q(`DELETE FROM workspaces WHERE id = ANY($1::uuid[])`, [[ids.wsA, ids.wsB]]);
  await q(`DELETE FROM organizations WHERE id = $1`, [ids.org]);
});

test("prima della riga: ogni prova a secco non scrive; i comandi dopo config chiedono la riga", opts, async () => {
  await dryRunsWriteNothing("senza riga", everyDryRun());
  const config = await run(["config", "--workspace", ids.wsA, "--file", configFile]);
  assert.equal(config.output.status, "DRY_RUN");
  assert.equal(config.output.riga, "nuova (spenta)");
  for (const command of ["profile", "guide", "token", "backfill-codes"]) {
    const argv = command === "token" || command === "backfill-codes" ? [command, "--workspace", ids.wsA] : [command, "--workspace", ids.wsA, "--file", command === "guide" ? GUIDE_FILE : profileFile];
    assert.equal((await run(argv)).output.code, "config_mancante", command);
  }
});

test("--apply: senza le conferme giuste non scrive nulla", opts, async () => {
  const before = await snapshot();
  const cases: Array<[string[], string]> = [
    [["config", "--workspace", ids.wsA, "--file", configFile, "--apply", "--environment", "local", "--confirm-database", fingerprintDb], "conferma"],
    [["config", "--workspace", ids.wsA, "--file", configFile, ...confirmations("local", "127.0.0.1:55469/un_altro_database")], "database"],
    [["config", "--workspace", ids.wsA, "--file", configFile, ...confirmations("production"), "--production-approved"], "ambiente"],
    [["config", "--workspace", ids.wsA, "--file", configFile, ...confirmations("preview")], "ambiente"],
  ];
  for (const [argv, code] of cases) {
    const out = await run(argv);
    assert.equal(out.output.code, code, JSON.stringify(out.output));
    assert.equal(out.exitCode, 1);
  }
  // Senza la variabile lo script si ferma, anche a secco: mai DATABASE_URL.
  const noEnv = await admin(["config", "--workspace", ids.wsA, "--file", configFile], { env: { DATABASE_URL: url } });
  assert.equal(noEnv.output.code, "database");
  assert.equal(await snapshot(), before);
});

test("config, profilo, guida, codici e token: prove a secco tra un passo e l'altro senza scritture", opts, async () => {
  const config = await run(["config", "--workspace", ids.wsA, "--file", configFile, ...confirmations()]);
  assert.equal(config.output.status, "APPLIED", JSON.stringify(config.output));
  assert.equal(config.printed[0].status, "PLAN");
  const row = (await q(`SELECT slug, code_prefix, enabled, next_code_seq, workspace_display_name, allowed_domains FROM workspace_connector_configs WHERE workspace_id = $1`, [ids.wsA]))[0];
  assert.deepEqual(row, { slug, code_prefix: "XK", enabled: false, next_code_seq: 0, workspace_display_name: "Alfa e Beta", allowed_domains: ["alfa.test"] });
  await dryRunsWriteNothing("dopo config", everyDryRun());
  assert.equal((await run(["config", "--workspace", ids.wsA, "--file", configFile, ...confirmations()])).output.status, "NOTHING_TO_DO");
  assert.equal((await run(["guide", "--workspace", ids.wsA, "--file", GUIDE_FILE])).output.code, "profilo_mancante");

  const profile = await run(["profile", "--workspace", ids.wsA, "--file", profileFile, ...confirmations()]);
  assert.equal(profile.output.status, "APPLIED", JSON.stringify(profile.output));
  const stored = (await q(`SELECT profile, instructions_template FROM workspace_connector_configs WHERE workspace_id = $1`, [ids.wsA]))[0];
  assert.equal(stored.instructions_template, EXAMPLE_INSTRUCTIONS_TEMPLATE);
  assert.equal(Object.hasOwn(stored.profile as object, "instructionsTemplate"), false);
  await dryRunsWriteNothing("dopo profile", everyDryRun());

  const guide = await run(["guide", "--workspace", ids.wsA, "--file", GUIDE_FILE, ...confirmations()]);
  assert.equal(guide.output.status, "APPLIED", JSON.stringify(guide.output));
  const guideRow = (await q(`SELECT guide_version, guide -> 'agentCatalog' -> 0 ->> 'id' AS agent FROM workspace_connector_configs WHERE workspace_id = $1`, [ids.wsA]))[0];
  assert.deepEqual(guideRow, { guide_version: "2026-10.1", agent: "atlante" });
  assert.equal((await run(["guide", "--workspace", ids.wsA, "--file", GUIDE_FILE, ...confirmations()])).output.status, "NOTHING_TO_DO");
  await dryRunsWriteNothing("dopo guide", everyDryRun());

  // Codici: la prova a secco mostra quelli previsti, l'applicazione li assegna in ordine d'invio.
  const dry = await run(["backfill-codes", "--workspace", ids.wsA]);
  assert.deepEqual((dry.output.elenco as Array<{ codice: string; titolo: string }>).map((e) => [e.codice, e.titolo]), [
    ["XK-0001", TITLES[2]],
    ["XK-0002", TITLES[0]],
    ["XK-0003", TITLES[1]],
  ]);
  const codes = await run(["backfill-codes", "--workspace", ids.wsA, ...confirmations()]);
  assert.equal(codes.output.status, "APPLIED");
  assert.equal(codes.output.assegnati, 3);
  const assigned = await q(`SELECT title, code FROM use_cases WHERE workspace_id = $1 ORDER BY code`, [ids.wsA]);
  assert.deepEqual(assigned.map((r) => [r.code, r.title]), [["XK-0001", TITLES[2]], ["XK-0002", TITLES[0]], ["XK-0003", TITLES[1]]]);
  assert.equal((await run(["backfill-codes", "--workspace", ids.wsA, ...confirmations()])).output.status, "NOTHING_TO_DO");
  await dryRunsWriteNothing("dopo backfill-codes", everyDryRun());

  // Token: stampato una volta; in tabella hash, inizio, i due scope, 90 giorni, nessun creatore.
  const created = await run(["token", "--workspace", ids.wsA, "--label", "Connettore di prova K8", ...confirmations()]);
  assert.equal(created.output.status, "APPLIED");
  token = String(created.output.token);
  assert.ok(token.startsWith(CONNECTOR_TOKEN_PREFIX) && /^[A-Za-z0-9_-]{43}$/.test(token.slice(CONNECTOR_TOKEN_PREFIX.length)));
  assert.equal(JSON.stringify(created.printed).includes(token), false);
  const tokenRow = (await q(
    `SELECT token_hash, token_prefix, provider, scopes, created_by_user_id, revoked_at,
            round(extract(epoch FROM expires_at - (now() AT TIME ZONE 'UTC')) / 86400) AS days
       FROM workspace_integration_tokens WHERE workspace_id = $1`,
    [ids.wsA]
  ))[0];
  assert.equal(tokenRow.token_hash, createHash("sha256").update(token, "utf8").digest("hex"));
  assert.equal(tokenRow.token_prefix, `${token.slice(0, 14)}...`);
  assert.equal(tokenRow.provider, "claude_connector");
  assert.deepEqual(tokenRow.scopes, ["connector:read", "connector:submit"]);
  assert.equal(tokenRow.created_by_user_id, null);
  assert.equal(Number(tokenRow.days), 90);
  await dryRunsWriteNothing("dopo token", everyDryRun());
});

