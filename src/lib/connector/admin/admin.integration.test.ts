test("la rotta serve ciò che lo script ha caricato: istruzioni, tool del profilo, guida, ricerca senza accenti", opts, async () => {
  assert.ok(token, "il token nasce nel test precedente");
  // Lateral Space accende il connettore dalla scheda «Connettore Claude».
  await q(`UPDATE workspace_connector_configs SET enabled = true WHERE workspace_id = $1`, [ids.wsA]);
  const transport = new StreamableHTTPClientTransport(new URL(`http://127.0.0.1:53130/api/mcp/connettore/${slug}`), {
    fetch: async (input: string | URL, init?: RequestInit) => handle(new Request(input, init), slug, routeDeps),
    requestInit: { headers: { authorization: `Bearer ${token}` } },
  });
  const client = new Client({ name: "prova-k8", version: "1.0.0" });
  await client.connect(transport);
  try {
    assert.equal(client.getInstructions(), connectorServerInstructions("Alfa e Beta", EXAMPLE_INSTRUCTIONS_TEMPLATE));
    const { tools } = await client.listTools();
    assert.deepEqual(tools.map((t) => t.title), Object.values(EXAMPLE_TOOL_TEXTS).map((t) => t.title));
    const guide = (await client.callTool({ name: "get_intake_guide", arguments: {} })).structuredContent as Record<string, unknown>;
    const file = JSON.parse(readFileSync(GUIDE_FILE, "utf8")) as Record<string, unknown>;
    assert.equal(guide.guideVersion, "2026-10.1");
    assert.equal(guide.identityMode, "dichiarata");
    assert.deepEqual(guide.agentCatalog, file.agentCatalog);
    assert.deepEqual(guide.rubric, file.rubric);
    const found = (await client.callTool({ name: "find_similar_contributions", arguments: { query: "qualita" } })).structuredContent as {
      results: Array<{ code: string }>;
    };
    assert.deepEqual(found.results.map((r) => r.code), ["XK-0002"]);
  } finally {
    await client.close();
  }
  assert.equal(captured.some((line) => line.includes(token)), false, "il token non finisce nel log");
});

test("profilo e guida insieme: beneficiariesMax 50 → 80 in un solo UPDATE, dopo i rifiuti di profile e guide da soli", opts, async () => {
  const profile80 = join(dir, "profilo-80.json");
  writeFileSync(profile80, JSON.stringify({ ...EXAMPLE_PROFILE_FILE, contract: { ...EXAMPLE_PROFILE, beneficiariesMax: 80 } }));
  const guide = JSON.parse(readFileSync(GUIDE_FILE, "utf8")) as Record<string, unknown>;
  guide.guideVersion = "2026-10.2";
  guide.beneficiaryCap = 80;
  guide.fields = (guide.fields as Array<Record<string, unknown>>).map((f) => (f.name === "beneficiaries" ? { ...f, max: 80 } : f));
  const guide80 = join(dir, "guida-80.json");
  writeFileSync(guide80, JSON.stringify(guide));

  const before = await snapshot();
  assert.equal((await run(["profile", "--workspace", ids.wsA, "--file", profile80, ...confirmations()])).output.code, "guida_profilo");
  assert.equal((await run(["guide", "--workspace", ids.wsA, "--file", guide80, ...confirmations()])).output.code, "guida_profilo");
  await dryRunsWriteNothing("profilo e guida insieme", [["profile", "--workspace", ids.wsA, "--file", profile80, "--guide-file", guide80]]);
  assert.equal(await snapshot(), before, "i rifiuti non scrivono");

  const applied = await run(["profile", "--workspace", ids.wsA, "--file", profile80, "--guide-file", guide80, ...confirmations()]);
  assert.equal(applied.output.status, "APPLIED", JSON.stringify(applied.output));
  const row = (await q(
    `SELECT profile -> 'contract' ->> 'beneficiariesMax' AS max, guide ->> 'beneficiaryCap' AS cap, guide_version, instructions_template = $2 AS same_template
       FROM workspace_connector_configs WHERE workspace_id = $1`,
    [ids.wsA, EXAMPLE_INSTRUCTIONS_TEMPLATE]
  ))[0];
  assert.deepEqual(row, { max: "80", cap: "80", guide_version: "2026-10.2", same_template: true });
  assert.equal((await run(["profile", "--workspace", ids.wsA, "--file", profile80, "--guide-file", guide80, ...confirmations()])).output.status, "NOTHING_TO_DO");
  assert.equal((await run(["guide", "--workspace", ids.wsA, "--file", guide80, ...confirmations()])).output.status, "NOTHING_TO_DO", "ora la guida è coerente con il profilo salvato");
});

test("lo script vero: prova a secco da riga di comando, uscita JSON, nessuna scrittura; scoring-model passa all'hub", opts, async () => {
  const before = await snapshot();
  const env = {
    PATH: process.env.PATH ?? "/usr/bin:/bin",
    HOME: process.env.HOME ?? "/private/tmp",
    NODE_OPTIONS: "--require=./scripts/uc-test/local-neon.cjs",
    UC_TEST_DATABASE_URL: url!,
    UC_TEST_PG_PORT: process.env.UC_TEST_PG_PORT ?? "55469",
    UC_TEST_PG_DB: process.env.UC_TEST_PG_DB ?? "unbundle_conn_test",
    CONNECTOR_ADMIN_DATABASE_URL: url!,
  };
  // Ambiente chiuso: solo il database locale, niente DATABASE_URL (NODE_ENV lo vuole il tipo di Next, non lo script).
  const script = (args: string[]) =>
    spawnSync(process.execPath, ["--no-warnings", "scripts/connector-admin.ts", ...args], { cwd: repoRoot, env: env as unknown as NodeJS.ProcessEnv, encoding: "utf8" });
  const dry = script(["backfill-codes", "--workspace", ids.wsA]);
  assert.equal(dry.status, 0, dry.stderr);
  assert.equal(JSON.parse(dry.stdout).status, "NOTHING_TO_DO");
  const config = script(["config", "--workspace", ids.wsA, "--file", configFile]);
  assert.equal(config.status, 0, config.stderr);
  const out = JSON.parse(config.stdout);
  assert.equal(out.status, "NOTHING_TO_DO");
  assert.equal(out.database, fingerprintDb);
  const refused = script(["token", "--workspace", ids.wsA, "--apply"]);
  assert.equal(refused.status, 1);
  assert.equal(JSON.parse(refused.stdout).code, "conferma");
  const deferred = script(["scoring-model", "--workspace", ids.wsA]);
  assert.equal(deferred.status, 1);
  assert.equal(JSON.parse(deferred.stdout).status, "NOT_AVAILABLE");
  assert.equal(await snapshot(), before);
});
